import { useMemo, useRef, useState, type RefObject } from 'react';
import { useNavigate } from 'react-router-dom';
import { Archive, FlaskConical, Play, Upload } from 'lucide-react';
import { errorText } from '@/api/client';
import { useCreateFromScenario, useCreateIncident, useDiagnose, useMeta, useProfiles, useScenarios, useUploadArchive, useUploadTelemetry } from '@/api/hooks';
import type { IngestionReport } from '@/api/types';
import { useApp } from '@/state/settings';
import { Chip, Empty, ErrorState, Loading, Panel } from '@/components/ui';

export default function ScenariosPage() {
  return (
    <>
      <div className="page-head">
        <div><h1>Scenarios &amp; upload</h1><p>Run a documented synthetic scenario, or upload your own topology and telemetry. Only NDEP JSON and profile-mapped CSV are accepted.</p></div>
      </div>
      <ScenarioGrid />
      <UploadPanel />
    </>
  );
}

function ScenarioGrid() {
  const sc = useScenarios();
  const { preview, set } = useApp();
  const nav = useNavigate();
  const create = useCreateFromScenario();
  const diagnose = useDiagnose();
  const [verify, setVerify] = useState(true);
  const [q, setQ] = useState('');
  const [busy, setBusy] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const list = useMemo(() => (sc.data?.scenarios ?? []).filter((s) => !q || `${s.scenario_id} ${s.title} ${s.tags.join(' ')}`.toLowerCase().includes(q.toLowerCase())), [sc.data, q]);
  const run = async (sid: string) => {
    setErr(null);
    setBusy(sid);
    try {
      const r = await create.mutateAsync(sid);
      await diagnose.mutateAsync({ id: r.incident.incident_id, verification: verify });
      set({ activeIncidentId: r.incident.incident_id, selectedScenarioId: sid });
      nav('/');
    } catch (e) {
      setErr(errorText(e));
    } finally {
      setBusy(null);
    }
  };
  return (
    <Panel title="Scenario library" icon={<FlaskConical size={19} />} sub={sc.data ? `${list.length} of ${sc.data.scenarios.length} · all synthetic, generated by the project's own generator` : undefined}
           actions={<>
             <input className="input" style={{ width: 240 }} placeholder="Search id, title, tag…" value={q} onChange={(e) => setQ(e.target.value)} aria-label="Search scenarios" />
             <label className="check"><input type="checkbox" checked={verify} onChange={(e) => setVerify(e.target.checked)} />Targeted verification</label>
           </>}>
      {err && <div className="err" style={{ marginBottom: 10 }}>{err}</div>}
      {sc.isLoading ? <Loading /> : sc.isError ? <ErrorState error={sc.error} /> : list.length === 0 ? <Empty title="No scenarios match" /> : (
        <div className="cols-3" style={{ gap: 10 }}>
          {list.map((s) => (
            <div key={s.scenario_id} className="hyp" style={{ gridTemplateColumns: '1fr', cursor: 'default', alignContent: 'start' }}>
              <div className="mono faint" style={{ fontSize: 12 }}>{s.scenario_id}{s.split ? ` · ${s.split}` : ''}</div>
              <div className="hyp-name">{s.title}</div>
              <div className="chips">
                <Chip tone="muted">{s.data_mode}</Chip>
                {s.tags.map((t) => <Chip key={t} tone="cyan">{t}</Chip>)}
                {s.has_archive && <Chip tone="violet" title="Includes a recorded archive that agents can query during verification">archive</Chip>}
                {s.telemetry_profile && <Chip tone="blue" title="Telemetry is a CSV export mapped by this source profile">{s.telemetry_profile}</Chip>}
              </div>
              <div className="panel-sub">{s.source_description}</div>
              <button className="btn primary sm" style={{ justifySelf: 'start', marginTop: 4 }} disabled={preview || !!busy} onClick={() => run(s.scenario_id)}
                      title={preview ? 'Not available in the recorded preview' : undefined}>
                <Play size={14} />{busy === s.scenario_id ? 'Starting…' : 'Create & diagnose'}
              </button>
            </div>
          ))}
        </div>
      )}
    </Panel>
  );
}

const readFile = (f: File) => f.text();

function UploadPanel() {
  const { preview, set } = useApp();
  const nav = useNavigate();
  const meta = useMeta();
  const profiles = useProfiles();
  const createInc = useCreateIncident();
  const upTel = useUploadTelemetry();
  const upArc = useUploadArchive();
  const diagnose = useDiagnose();
  const [mode, setMode] = useState('recorded');
  const [title, setTitle] = useState('');
  const [refTime, setRefTime] = useState('');
  const [profile, setProfile] = useState('');
  const [verify, setVerify] = useState(true);
  const topoRef = useRef<HTMLInputElement>(null);
  const telRef = useRef<HTMLInputElement>(null);
  const arcRef = useRef<HTMLInputElement>(null);
  const [files, setFiles] = useState<{ topo?: File; tel?: File; arc?: File }>({});
  const [step, setStep] = useState<string | null>(null);
  const [err, setErr] = useState<string | null>(null);
  const [result, setResult] = useState<{ id: string; ingestion: IngestionReport; archive?: { archive_ref: string; batches: number } } | null>(null);
  const maxBytes = meta.data?.max_upload_bytes;
  const tooBig = (f?: File) => !!(f && maxBytes && f.size > maxBytes);

  const submit = async () => {
    setErr(null);
    setResult(null);
    if (!files.tel) return setErr('Choose a telemetry file.');
    if (profile && !files.tel.name.toLowerCase().endsWith('.csv')) return setErr('A source profile maps CSV; choose a .csv file or select "NDEP JSON".');
    if (!profile && !files.tel.name.toLowerCase().endsWith('.json')) return setErr('Without a source profile, telemetry must be an NDEP TelemetryBatch .json file.');
    if ([files.topo, files.tel, files.arc].some(tooBig)) return setErr(`A file is larger than the backend limit of ${Math.round((maxBytes ?? 0) / 1048576)} MiB.`);
    let topology: unknown;
    if (files.topo) {
      try {
        topology = JSON.parse(await readFile(files.topo));
      } catch {
        return setErr('Topology file is not valid JSON.');
      }
    }
    if (refTime && Number.isNaN(Date.parse(refTime))) return setErr('Reference time must be an ISO-8601 timestamp, e.g. 2026-10-31T10:00:05Z.');
    try {
      setStep('Creating incident…');
      const inc = await createInc.mutateAsync({ data_mode: mode, title: title || undefined, topology, reference_time: refTime || undefined });
      const id = inc.incident.incident_id;
      setStep('Uploading telemetry…');
      const ingestion = await upTel.mutateAsync({ id, text: await readFile(files.tel), profile: profile || undefined });
      let archive;
      if (files.arc) {
        setStep('Uploading archive…');
        archive = await upArc.mutateAsync({ id, text: await readFile(files.arc) });
      }
      setResult({ id, ingestion, archive });
      set({ activeIncidentId: id });
    } catch (e) {
      setErr(errorText(e));
    } finally {
      setStep(null);
    }
  };
  const runIt = async () => {
    if (!result) return;
    setErr(null);
    try {
      await diagnose.mutateAsync({ id: result.id, verification: verify });
      nav('/');
    } catch (e) {
      setErr(errorText(e));
    }
  };
  const fileBox = (key: 'topo' | 'tel' | 'arc', ref: RefObject<HTMLInputElement | null>, label: string, accept: string, hint: string) => (
    <div>
      <input ref={ref} type="file" accept={accept} hidden onChange={(e) => setFiles((f) => ({ ...f, [key]: e.target.files?.[0] }))} aria-label={label} />
      <div className="drop" role="button" tabIndex={0} onClick={() => ref.current?.click()} onKeyDown={(e) => (e.key === 'Enter' || e.key === ' ') && ref.current?.click()}>
        <div style={{ fontWeight: 620, color: 'var(--text)' }}>{label}</div>
        <div className="mono" style={{ fontSize: 12.5, marginTop: 4, color: files[key] ? (tooBig(files[key]) ? 'var(--red)' : 'var(--cyan)') : undefined }}>
          {files[key] ? `${files[key]!.name} · ${(files[key]!.size / 1024).toFixed(1)} KiB` : hint}
        </div>
      </div>
    </div>
  );
  return (
    <Panel title="Upload telemetry" icon={<Upload size={19} />} className="" sub={`Validated by the evidence fabric; rejected and quarantined records are reported, never coerced${maxBytes ? ` · max ${Math.round(maxBytes / 1048576)} MiB per file` : ''}`}>
      <div id="upload" />
      {preview && <div className="err" style={{ marginBottom: 10 }}>Uploads are disabled in the recorded preview. Connect to a backend in Settings.</div>}
      <div className="cols-2">
        <div className="stack" style={{ gap: 10 }}>
          <label className="field">Data mode
            <select className="select" value={mode} onChange={(e) => setMode(e.target.value)}>
              <option value="recorded">recorded</option><option value="emulated">emulated</option><option value="synthetic">synthetic</option>
            </select>
          </label>
          <label className="field">Title<input className="input" value={title} onChange={(e) => setTitle(e.target.value)} placeholder="e.g. Floor 2 Wi-Fi outage" /></label>
          <label className="field">Reference time (ISO-8601, optional)<input className="input" value={refTime} onChange={(e) => setRefTime(e.target.value)} placeholder="2026-10-31T10:00:05Z" /></label>
          <label className="field">Telemetry format
            <select className="select" value={profile} onChange={(e) => setProfile(e.target.value)}>
              <option value="">NDEP TelemetryBatch (JSON)</option>
              {(profiles.data?.profiles ?? []).map((p) => <option key={p.profile_id} value={p.profile_id}>CSV via profile {p.profile_id} v{p.version}</option>)}
            </select>
          </label>
          {profile && <div className="panel-sub">{profiles.data?.profiles.find((p) => p.profile_id === profile)?.description}</div>}
        </div>
        <div className="stack" style={{ gap: 10 }}>
          {fileBox('topo', topoRef, 'Topology (JSON, optional)', '.json,application/json', 'Without topology, localization is limited')}
          {fileBox('tel', telRef, 'Telemetry (required)', profile ? '.csv,text/csv' : '.json,application/json', profile ? 'CSV export matching the profile' : 'NDEP TelemetryBatch JSON')}
          {fileBox('arc', arcRef, 'Recorded archive (JSON, optional)', '.json,application/json', meta.data && !meta.data.uploads_archive_enabled ? 'Archive uploads are disabled on this backend' : '{"batches": [TelemetryBatch…]} agents may query')}
          <button className="btn primary" disabled={preview || !!step} onClick={submit}><Upload size={16} />{step ?? 'Validate & ingest'}</button>
        </div>
      </div>
      {err && <div className="err" style={{ marginTop: 12 }}>{err}</div>}
      {result && <IngestionResult r={result.ingestion} archive={result.archive} verify={verify} setVerify={setVerify} onRun={runIt} running={diagnose.isPending} />}
    </Panel>
  );
}

function IngestionResult({ r, archive, verify, setVerify, onRun, running }: { r: IngestionReport; archive?: { archive_ref: string; batches: number }; verify: boolean; setVerify: (v: boolean) => void; onRun: () => void; running: boolean }) {
  const c = r.counts;
  return (
    <div className="stack" style={{ marginTop: 14, gap: 10 }}>
      <div style={{ fontWeight: 650 }}>Ingestion report · <span className="mono">{r.incident_id}</span></div>
      <div className="chips">
        <Chip tone="muted">{c.records} record(s)</Chip>
        <Chip tone="green">{c.accepted} accepted</Chip>
        {c.partially_rejected > 0 && <Chip tone="amber">{c.partially_rejected} partially rejected</Chip>}
        {c.quarantined > 0 && <Chip tone="amber">{c.quarantined} quarantined</Chip>}
        {c.rejected > 0 && <Chip tone="red">{c.rejected} rejected</Chip>}
        {c.duplicate > 0 && <Chip tone="muted">{c.duplicate} duplicate</Chip>}
        {c.conflict > 0 && <Chip tone="red">{c.conflict} conflict</Chip>}
        <Chip tone="cyan">{r.observations_added} observations added</Chip>
        {archive && <Chip tone="violet"><Archive size={12} /> archive: {archive.batches} batch(es)</Chip>}
      </div>
      {r.issues.length > 0 && (
        <div className="table-wrap" style={{ maxHeight: 260 }}>
          <table className="t">
            <thead><tr><th>Severity</th><th>Code</th><th>Record</th><th>Path</th><th>Message</th></tr></thead>
            <tbody>{r.issues.map((i, k) => (
              <tr key={k}>
                <td><Chip tone={i.severity === 'reject' ? 'red' : i.severity === 'quarantine' ? 'amber' : 'muted'}>{i.severity}</Chip></td>
                <td className="mono">{i.code}</td><td className="mono faint">{i.record_id ?? i.record_index ?? '—'}</td>
                <td className="mono faint">{i.path ?? '—'}</td><td>{i.message}</td>
              </tr>
            ))}</tbody>
          </table>
        </div>
      )}
      <div style={{ display: 'flex', gap: 12, alignItems: 'center', flexWrap: 'wrap' }}>
        <label className="check"><input type="checkbox" checked={verify} onChange={(e) => setVerify(e.target.checked)} />Targeted verification</label>
        <button className="btn primary" onClick={onRun} disabled={running || r.observations_added === 0}
                title={r.observations_added === 0 ? 'No observations were accepted' : undefined}><Play size={16} />Run diagnosis</button>
      </div>
    </div>
  );
}
